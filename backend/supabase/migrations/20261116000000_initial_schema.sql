create type public.user_role as enum ('student', 'admin');
create type public.game_type as enum ('single', 'team');

create table public.users (
  user_id bigint generated by default as identity primary key,
  auth_user_id uuid not null unique references auth.users (id) on delete cascade,
  name varchar(100) not null,
  email varchar(150) not null unique,
  role public.user_role not null default 'student',
  created_at timestamptz not null default now()
);

create table public.events (
  event_id bigint generated by default as identity primary key,
  event_name varchar(150) not null,
  description text,
  category varchar(80) not null default 'Community',
  game_type public.game_type not null,
  event_date date not null,
  start_time time not null,
  venue varchar(200) not null,
  capacity integer not null check (capacity > 0),
  created_by_admin bigint not null references public.users (user_id) on delete restrict,
  created_at timestamptz not null default now()
);

create table public.teams (
  team_id bigint generated by default as identity primary key,
  team_name varchar(100) not null unique,
  leader_id bigint not null references public.users (user_id) on delete cascade,
  created_at timestamptz not null default now()
);

create table public.team_members (
  team_id bigint not null references public.teams (team_id) on delete cascade,
  student_id bigint not null references public.users (user_id) on delete cascade,
  joined_at timestamptz not null default now(),
  primary key (team_id, student_id)
);

create table public.registrations (
  registration_id bigint generated by default as identity primary key,
  event_id bigint not null references public.events (event_id) on delete cascade,
  student_id bigint references public.users (user_id) on delete cascade,
  team_id bigint references public.teams (team_id) on delete cascade,
  registered_at timestamptz not null default now(),
  constraint registration_subject_check check (
    (student_id is not null and team_id is null)
    or (student_id is null and team_id is not null)
  ),
  constraint registration_event_student_unique unique (event_id, student_id),
  constraint registration_event_team_unique unique (event_id, team_id)
);

create index events_event_date_idx on public.events (event_date, start_time);
create index registrations_event_id_idx on public.registrations (event_id);
create index team_members_student_id_idx on public.team_members (student_id);

create or replace function public.create_user_profile()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.users (auth_user_id, name, email, role)
  values (
    new.id,
    left(coalesce(nullif(trim(new.raw_user_meta_data ->> 'name'), ''), split_part(new.email, '@', 1)), 100),
    left(lower(new.email), 150),
    'student'
  )
  on conflict (auth_user_id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.create_user_profile();

create or replace view public.event_registration_summary
with (security_invoker = true)
as
select
  event.event_id,
  count(registration.registration_id)::integer as registration_count,
  coalesce(
    sum(
      case
        when registration.student_id is not null then 1
        when registration.team_id is not null then (
          select count(*) from public.team_members member
          where member.team_id = registration.team_id
        )
        else 0
      end
    ),
    0
  )::integer as attendee_count
from public.events event
left join public.registrations registration on registration.event_id = event.event_id
group by event.event_id;

create or replace function public.register_single_event(p_event_id bigint, p_student_id bigint)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_event public.events%rowtype;
  current_attendees integer;
  new_registration_id bigint;
begin
  select * into target_event
  from public.events
  where event_id = p_event_id
  for update;

  if not found then
    raise exception 'Event not found' using errcode = 'P0002';
  end if;
  if target_event.game_type <> 'single' then
    raise exception 'This event requires a team registration' using errcode = '22023';
  end if;
  if not exists (
    select 1 from public.users
    where user_id = p_student_id and role = 'student'
  ) then
    raise exception 'A valid student account is required' using errcode = '42501';
  end if;

  select coalesce(sum(
    case
      when registration.student_id is not null then 1
      when registration.team_id is not null then (
        select count(*) from public.team_members member
        where member.team_id = registration.team_id
      )
      else 0
    end
  ), 0)::integer into current_attendees
  from public.registrations registration
  where registration.event_id = p_event_id;

  if current_attendees >= target_event.capacity then
    raise exception 'Event is full' using errcode = '23514';
  end if;

  insert into public.registrations (event_id, student_id)
  values (p_event_id, p_student_id)
  returning registration_id into new_registration_id;

  return new_registration_id;
end;
$$;

create or replace function public.register_team_event(
  p_event_id bigint,
  p_leader_id bigint,
  p_team_name text,
  p_member_ids bigint[]
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_event public.events%rowtype;
  normalized_member_ids bigint[];
  current_teams integer;
  new_team_id bigint;
  new_registration_id bigint;
begin
  select * into target_event
  from public.events
  where event_id = p_event_id
  for update;

  if not found then
    raise exception 'Event not found' using errcode = 'P0002';
  end if;
  if target_event.game_type <> 'team' then
    raise exception 'This event accepts individual registration' using errcode = '22023';
  end if;
  if not exists (
    select 1 from public.users
    where user_id = p_leader_id and role = 'student'
  ) then
    raise exception 'A valid student account is required' using errcode = '42501';
  end if;
  if nullif(trim(p_team_name), '') is null or length(trim(p_team_name)) > 100 then
    raise exception 'Team name must be between 1 and 100 characters' using errcode = '22023';
  end if;

  select array_agg(distinct member_id order by member_id)
  into normalized_member_ids
  from unnest(coalesce(p_member_ids, array[]::bigint[])) as members(member_id);

  if coalesce(cardinality(normalized_member_ids), 0) = 0
    or not (p_leader_id = any(normalized_member_ids)) then
    raise exception 'The team leader must be included in the member list' using errcode = '22023';
  end if;

  if (
    select count(*) from public.users
    where user_id = any(normalized_member_ids) and role = 'student'
  ) <> cardinality(normalized_member_ids) then
    raise exception 'All team members must be student accounts' using errcode = '22023';
  end if;

  if exists (
    select 1
    from public.registrations registration
    left join public.team_members member on member.team_id = registration.team_id
    where registration.event_id = p_event_id
      and (
        registration.student_id = any(normalized_member_ids)
        or member.student_id = any(normalized_member_ids)
      )
  ) then
    raise exception 'A team member is already registered for this event' using errcode = '23505';
  end if;

  select count(*)::integer into current_teams
  from public.registrations registration
  where registration.event_id = p_event_id
    and registration.team_id is not null;

  if current_teams >= target_event.capacity then
    raise exception 'No team places remain for this event' using errcode = '23514';
  end if;

  insert into public.teams (team_name, leader_id)
  values (trim(p_team_name), p_leader_id)
  returning team_id into new_team_id;

  insert into public.team_members (team_id, student_id)
  select new_team_id, unnest(normalized_member_ids);

  insert into public.registrations (event_id, team_id)
  values (p_event_id, new_team_id)
  returning registration_id into new_registration_id;

  return new_registration_id;
end;
$$;

