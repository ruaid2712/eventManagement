create table if not exists public.event_team_members (
  event_id bigint not null references public.events (event_id) on delete cascade,
  team_id bigint not null references public.teams (team_id) on delete cascade,
  student_id bigint not null references public.users (user_id) on delete cascade,
  joined_at timestamptz not null default now(),
  primary key (event_id, team_id, student_id),
  foreign key (event_id, team_id)
    references public.registrations (event_id, team_id) on delete cascade
);

insert into public.event_team_members (event_id, team_id, student_id, joined_at)
select registration.event_id, registration.team_id, member.student_id, member.joined_at
from public.registrations registration
join public.team_members member on member.team_id = registration.team_id
where registration.team_id is not null
on conflict (event_id, team_id, student_id) do nothing;

create index if not exists event_team_members_student_idx
on public.event_team_members (student_id, event_id);

alter table public.event_team_members enable row level security;
grant all on public.event_team_members to service_role;

create table if not exists public.team_join_requests (
  request_id bigint generated by default as identity primary key,
  team_id bigint not null references public.teams (team_id) on delete cascade,
  event_id bigint not null references public.events (event_id) on delete cascade,
  student_id bigint not null references public.users (user_id) on delete cascade,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  foreign key (event_id, team_id)
    references public.registrations (event_id, team_id) on delete cascade
);

create unique index if not exists team_join_requests_pending_unique
on public.team_join_requests (event_id, student_id)
where status = 'pending';

alter table public.team_join_requests enable row level security;
grant all on public.team_join_requests to service_role;
grant usage, select on sequence public.team_join_requests_request_id_seq to service_role;

create or replace view public.event_registration_summary
with (security_invoker = true)
as
select
  event.event_id,
  count(registration.registration_id)::integer as registration_count,
  coalesce(
    sum(
      case
        when registration.student_id is not null then 1
        when registration.team_id is not null then (
          select count(*) from public.event_team_members member
          where member.event_id = registration.event_id
            and member.team_id = registration.team_id
        )
        else 0
      end
    ),
    0
  )::integer as attendee_count
from public.events event
left join public.registrations registration on registration.event_id = event.event_id
group by event.event_id;

create or replace function public.register_team_event(
  p_event_id bigint,
  p_leader_id bigint,
  p_team_name text,
  p_member_ids bigint[]
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_event public.events%rowtype;
  normalized_member_ids bigint[];
  current_teams integer;
  new_team_id bigint;
  new_registration_id bigint;
begin
  select * into target_event
  from public.events
  where event_id = p_event_id
  for update;

  if not found then
    raise exception 'Event not found' using errcode = 'P0002';
  end if;
  if target_event.game_type <> 'team' then
    raise exception 'This event accepts individual registration' using errcode = '22023';
  end if;
  if not exists (
    select 1 from public.users
    where user_id = p_leader_id and role = 'student'
  ) then
    raise exception 'A valid student account is required' using errcode = '42501';
  end if;
  if nullif(trim(p_team_name), '') is null or length(trim(p_team_name)) > 100 then
    raise exception 'Team name must be between 1 and 100 characters' using errcode = '22023';
  end if;

  select array_agg(distinct member_id order by member_id)
  into normalized_member_ids
  from unnest(coalesce(p_member_ids, array[]::bigint[])) as members(member_id);

  if coalesce(cardinality(normalized_member_ids), 0) = 0
    or not (p_leader_id = any(normalized_member_ids)) then
    raise exception 'The team leader must be included in the member list' using errcode = '22023';
  end if;

  if (
    select count(*) from public.users
    where user_id = any(normalized_member_ids) and role = 'student'
  ) <> cardinality(normalized_member_ids) then
    raise exception 'All team members must be student accounts' using errcode = '22023';
  end if;

  if exists (
    select 1
    from public.registrations registration
    where registration.event_id = p_event_id
      and registration.student_id = any(normalized_member_ids)
  ) or exists (
    select 1
    from public.event_team_members member
    where member.event_id = p_event_id
      and member.student_id = any(normalized_member_ids)
  ) then
    raise exception 'A team member is already registered for this event' using errcode = '23505';
  end if;
  if exists (
    select 1 from public.team_join_requests join_request
    where join_request.event_id = p_event_id
      and join_request.student_id = any(normalized_member_ids)
      and join_request.status = 'pending'
  ) then
    raise exception 'A team member has a pending request to join another team for this event' using errcode = '23505';
  end if;

  select count(*)::integer into current_teams
  from public.registrations registration
  where registration.event_id = p_event_id
    and registration.team_id is not null;

  if current_teams >= target_event.capacity then
    raise exception 'No team places remain for this event' using errcode = '23514';
  end if;

  insert into public.teams (team_name, leader_id)
  values (trim(p_team_name), p_leader_id)
  returning team_id into new_team_id;

  insert into public.team_members (team_id, student_id)
  select new_team_id, unnest(normalized_member_ids);

  insert into public.registrations (event_id, team_id)
  values (p_event_id, new_team_id)
  returning registration_id into new_registration_id;

  insert into public.event_team_members (event_id, team_id, student_id)
  select p_event_id, new_team_id, unnest(normalized_member_ids);

  return new_registration_id;
end;
$$;

create or replace function public.request_team_withdrawal(
  p_event_id bigint,
  p_student_id bigint
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_event public.events%rowtype;
  target_team_id bigint;
  current_leader_id bigint;
  member_count bigint;
  new_request_id bigint;
begin
  select * into target_event
  from public.events
  where event_id = p_event_id
  for update;

  if not found then
    raise exception 'Event not found' using errcode = 'P0002';
  end if;
  if target_event.game_type <> 'team' then
    raise exception 'This event does not use team registration' using errcode = '22023';
  end if;

  select registration.team_id, team.leader_id
  into target_team_id, current_leader_id
  from public.registrations registration
  join public.teams team on team.team_id = registration.team_id
  join public.event_team_members member
    on member.event_id = registration.event_id
    and member.team_id = registration.team_id
    and member.student_id = p_student_id
  where registration.event_id = p_event_id
  for update of registration, team;

  if target_team_id is null then
    raise exception 'You are not registered for this event' using errcode = '22023';
  end if;

  if current_leader_id = p_student_id then
    select count(*) into member_count
    from public.event_team_members
    where event_id = p_event_id and team_id = target_team_id;

    if member_count = 1 then
      delete from public.registrations
      where event_id = p_event_id and team_id = target_team_id;

      delete from public.team_members legacy_member
      where legacy_member.team_id = target_team_id
        and not exists (
          select 1 from public.event_team_members member
          where member.team_id = legacy_member.team_id
            and member.student_id = legacy_member.student_id
        );

      if not exists (
        select 1 from public.registrations
        where team_id = target_team_id
      ) then
        delete from public.teams where team_id = target_team_id;
      end if;

      return jsonb_build_object('status', 'withdrawn');
    end if;

    raise exception 'Team leaders must transfer leadership before requesting withdrawal' using errcode = '22023';
  end if;

  insert into public.team_withdrawal_requests (team_id, event_id, student_id)
  values (target_team_id, p_event_id, p_student_id)
  on conflict (team_id, event_id, student_id) where status = 'pending'
  do nothing
  returning request_id into new_request_id;

  if new_request_id is null then
    select request_id into new_request_id
    from public.team_withdrawal_requests
    where team_id = target_team_id
      and event_id = p_event_id
      and student_id = p_student_id
      and status = 'pending';
  end if;

  return jsonb_build_object('status', 'pending', 'requestId', new_request_id);
end;
$$;

create or replace function public.review_team_withdrawal(
  p_request_id bigint,
  p_leader_id bigint,
  p_approve boolean
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_request public.team_withdrawal_requests%rowtype;
  current_leader_id bigint;
  target_event_id bigint;
begin
  select event_id into target_event_id
  from public.team_withdrawal_requests
  where request_id = p_request_id and status = 'pending';

  if not found then
    raise exception 'Pending withdrawal request not found' using errcode = 'P0002';
  end if;

  perform 1 from public.events
  where event_id = target_event_id
  for update;

  select * into target_request
  from public.team_withdrawal_requests
  where request_id = p_request_id and status = 'pending'
  for update;

  if not found then
    raise exception 'Pending withdrawal request not found' using errcode = 'P0002';
  end if;

  select leader_id into current_leader_id
  from public.teams
  where team_id = target_request.team_id
  for update;

  if current_leader_id is distinct from p_leader_id then
    raise exception 'Only the team leader can review withdrawal requests' using errcode = '42501';
  end if;

  update public.team_withdrawal_requests
  set status = case when p_approve then 'approved' else 'rejected' end,
      reviewed_at = now()
  where request_id = p_request_id;

  if p_approve then
    delete from public.event_team_members
    where event_id = target_request.event_id
      and team_id = target_request.team_id
      and student_id = target_request.student_id;

    delete from public.team_members legacy_member
    where legacy_member.team_id = target_request.team_id
      and legacy_member.student_id = target_request.student_id
      and not exists (
        select 1 from public.event_team_members member
        where member.team_id = legacy_member.team_id
          and member.student_id = legacy_member.student_id
      );
  end if;
end;
$$;

create or replace function public.request_team_join(
  p_event_id bigint,
  p_team_id bigint,
  p_student_id bigint
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_event public.events%rowtype;
  team_leader_id bigint;
  new_request_id bigint;
begin
  select * into target_event from public.events
  where event_id = p_event_id for update;

  if not found then
    raise exception 'Event not found' using errcode = 'P0002';
  end if;
  if target_event.game_type <> 'team' then
    raise exception 'This event does not accept team registrations' using errcode = '22023';
  end if;
  if not exists (
    select 1 from public.users
    where user_id = p_student_id and role = 'student'
  ) then
    raise exception 'A valid student account is required' using errcode = '42501';
  end if;

  select team.leader_id into team_leader_id
  from public.teams team
  join public.registrations registration
    on registration.team_id = team.team_id
   and registration.event_id = p_event_id
  where team.team_id = p_team_id
  for update of team;

  if not found then
    raise exception 'Team is not registered for this event' using errcode = 'P0002';
  end if;
  if team_leader_id = p_student_id then
    raise exception 'You are already the team leader' using errcode = '23505';
  end if;
  if exists (
    select 1 from public.registrations
    where event_id = p_event_id and student_id = p_student_id
  ) or exists (
    select 1 from public.event_team_members
    where event_id = p_event_id and student_id = p_student_id
  ) then
    raise exception 'You are already registered for a team in this event' using errcode = '23505';
  end if;
  if exists (
    select 1 from public.team_join_requests
    where event_id = p_event_id
      and student_id = p_student_id
      and team_id <> p_team_id
      and status = 'pending'
  ) then
    raise exception 'You already have a pending request to join another team for this event' using errcode = '23505';
  end if;

  insert into public.team_join_requests (team_id, event_id, student_id)
  values (p_team_id, p_event_id, p_student_id)
  on conflict (event_id, student_id) where status = 'pending'
  do nothing
  returning request_id into new_request_id;

  if new_request_id is null then
    select request_id into new_request_id
    from public.team_join_requests
    where team_id = p_team_id and event_id = p_event_id
      and student_id = p_student_id and status = 'pending';
  end if;

  return new_request_id;
end;
$$;

create or replace function public.review_team_join(
  p_request_id bigint,
  p_leader_id bigint,
  p_approve boolean
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_request public.team_join_requests%rowtype;
  current_leader_id bigint;
  target_event_id bigint;
begin
  select event_id into target_event_id
  from public.team_join_requests
  where request_id = p_request_id and status = 'pending';

  if not found then
    raise exception 'Pending team join request not found' using errcode = 'P0002';
  end if;

  perform 1 from public.events where event_id = target_event_id for update;

  select * into target_request
  from public.team_join_requests
  where request_id = p_request_id and status = 'pending'
  for update;

  if not found then
    raise exception 'Pending team join request not found' using errcode = 'P0002';
  end if;

  select leader_id into current_leader_id
  from public.teams
  where team_id = target_request.team_id
  for update;

  if current_leader_id is distinct from p_leader_id then
    raise exception 'Only the team leader can review join requests' using errcode = '42501';
  end if;

  if p_approve then
    if exists (
      select 1 from public.registrations
      where event_id = target_request.event_id and student_id = target_request.student_id
    ) or exists (
      select 1 from public.event_team_members
      where event_id = target_request.event_id and student_id = target_request.student_id
    ) then
      raise exception 'This student is already registered for a team in this event' using errcode = '23505';
    end if;

    insert into public.team_members (team_id, student_id)
    values (target_request.team_id, target_request.student_id)
    on conflict (team_id, student_id) do nothing;

    insert into public.event_team_members (event_id, team_id, student_id)
    values (target_request.event_id, target_request.team_id, target_request.student_id);
  end if;

  update public.team_join_requests
  set status = case when p_approve then 'approved' else 'rejected' end,
      reviewed_at = now()
  where request_id = p_request_id;
end;
$$;

